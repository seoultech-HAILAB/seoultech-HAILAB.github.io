"""Build redirects for the old CMS News and V-log URLs from known post IDs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROUTES = [
    ('20000007606', 'news2', 'nttSeq', 'board/news', '/board/index.html'),
    ('20000007599', 'vlog2', 'mvpnttSeq', 'board/vlog', '/board/vlog.html'),
    ('20000008703', 'gallery2', 'nttSeq', 'board/gallery', '/board/gallery.html'),
    ('20000008704', 'projects2', 'nttSeq', 'research/project', '/research/index.html'),
    ('20000008160', 'videos2', 'mvpnttSeq', 'research/video', '/research/videos.html'),
]
# Confirmed from the archived CMS navigation. Retired sections lead to their
# relevant current listing, never to an unverified post with the same numeric ID.
STATIC_ROUTES = {
    '20000007611': '/about/index.html',
    '20000008769': '/board/index.html',  # Lab log: same news in the initial Git version.
    '20000007966': '/about/facility.html',
    '20000008039': '/about/patents.html',
    '20000004988': '/members/index.html',
    '20000005638': '/members/researcher.html',
    '20000007648': '/members/alumni.html',
    '20000008725': '/members/history.html',
    '20000007954': '/publications/index.html',
    '20000006008': '/board/gallery.html',  # Older gallery IDs do not match migrated IDs.
    '20000008022': '/research/index.html',  # Retired seminars; no current exact counterpart.
    '20000008034': '/research/index.html',  # Archived pages identify only Research.
    '20000005608': '/research/index.html',
    '20000008054': '/research/index.html',
}


def static_page(destination):
    assert (ROOT / destination.lstrip('/')).is_file()
    return '''<!doctype html>
<!-- redirect-stub: generated by tools/build_legacy_board_redirects.py -->
<html lang="en"><head><meta charset="utf-8">
<title>Redirecting to SeoulTech HAI Lab</title>
<meta http-equiv="refresh" content="0;url=DEST">
<link rel="canonical" href="https://hai.seoultech.ac.krDEST">
<script>location.replace('DEST' + location.hash);</script>
</head><body><a href="DEST">Continue to the current section</a></body></html>
'''.replace('DEST', destination)


def build():
    posts = json.loads((ROOT / 'tools/post_index.json').read_text(encoding='utf-8'))
    for board, key, parameter, kind, listing in ROUTES:
        ids = [str(post['seq']) for post in posts[key]
               if (ROOT / post['href']).is_file()]
        page = '''<!doctype html>
<!-- redirect-stub: generated by tools/build_legacy_board_redirects.py -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Redirecting to SeoulTech HAI Lab</title>
</head>
<body>
<p><a id="destination" href="LISTING">Continue to SeoulTech HAI Lab</a></p>
<script>
(function () {
  var knownPosts = IDS;
  var id = new URLSearchParams(location.search).get('PARAMETER');
  var destination = knownPosts.indexOf(id) !== -1
    ? '/KIND/' + id + '.html' : 'LISTING';
  document.getElementById('destination').href = destination + location.hash;
  location.replace(destination + location.hash);
})();
</script>
</body>
</html>
'''
        page = (page.replace('IDS', json.dumps(ids)).replace('PARAMETER', parameter)
                .replace('KIND', kind).replace('LISTING', listing))
        path = ROOT / 'subList' / board / 'index.html'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(page, encoding='utf-8')
    for board, destination in STATIC_ROUTES.items():
        path = ROOT / 'subList' / board / 'index.html'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(static_page(destination), encoding='utf-8')
    for path, destination in [('about/lab-log.html', '/board/index.html'),
                              ('research/seminars.html', '/research/index.html')]:
        (ROOT / path).write_text(static_page(destination), encoding='utf-8')


if __name__ == '__main__':
    build()
